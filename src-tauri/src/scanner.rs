#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum RiskClassification {
    #[default]
    SafeToClean,
    ReviewRequired,
    Protected,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CategoryScanStatus {
    Pending,
    Scanning,
    Completed,
    Skipped,
    Error,
    Partial,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ScanCategory {
    SystemCaches,
    ApplicationLogs,
    DeveloperXcode,
    DeveloperCaches,
    BrowserCaches,
    MessagingCaches,
    UserTrash,
    MailDownloads,
    LargeFiles,
    Docker,
}

impl ScanCategory {
    pub fn display_name(&self) -> &'static str {
        match self {
            ScanCategory::SystemCaches => "System & App Caches",
            ScanCategory::ApplicationLogs => "Logs & Crash Reports",
            ScanCategory::DeveloperXcode => "Xcode DerivedData & Builds",
            ScanCategory::DeveloperCaches => "Developer Tooling Caches",
            ScanCategory::BrowserCaches => "Browser Web Caches",
            ScanCategory::MessagingCaches => "Messaging App Caches",
            ScanCategory::UserTrash => "macOS Trash Bin",
            ScanCategory::MailDownloads => "Mail Attachments & Caches",
            ScanCategory::LargeFiles => "Large & Old Files (>100MB)",
            ScanCategory::Docker => "Docker Clutter & Caches",
        }
    }

    pub fn default_description(&self) -> &'static str {
        match self {
            ScanCategory::SystemCaches => "Temporary cache data generated by macOS and applications that can safely be regenerated.",
            ScanCategory::ApplicationLogs => "Diagnostic crash logs, application telemetry, and outdated error logs.",
            ScanCategory::DeveloperXcode => "Xcode intermediate build products, simulator runtimes, and index caches.",
            ScanCategory::DeveloperCaches => "Homebrew bottle downloads, Cargo registry archives, and build artifacts.",
            ScanCategory::BrowserCaches => "Offline website assets, temporary image buffers, and cached scripts.",
            ScanCategory::MessagingCaches => "Downloaded audio messages, media thumbnails, and chat cache buffers.",
            ScanCategory::UserTrash => "Files currently sitting in your macOS Trash bin taking up storage.",
            ScanCategory::MailDownloads => "Temporary cached email attachments that were viewed or previewed.",
            ScanCategory::LargeFiles => "High-capacity files and archives older than 30 days.",
            ScanCategory::Docker => "Dangling Docker images and reusable build cache layers that can be pruned safely.",
        }
    }

    pub fn default_classification(&self) -> RiskClassification {
        match self {
            ScanCategory::LargeFiles | ScanCategory::Docker => RiskClassification::ReviewRequired,
            _ => RiskClassification::SafeToClean,
        }
    }

    pub fn is_safe_by_default(&self) -> bool {
        self.default_classification() == RiskClassification::SafeToClean
    }
}

